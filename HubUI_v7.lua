			local out = {}
			for _, n in ipairs(values) do if sel[tostring(n)] then out[#out + 1] = tostring(n) end end
			fire(o.Callback, out)
		else
			local cur
			for _, n in ipairs(values) do if sel[tostring(n)] then cur = tostring(n) end end
			fire(o.Callback, cur)
		end
	end
