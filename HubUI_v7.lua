	row.MouseLeave:Connect(function()
		tw(row, {BackgroundColor3 = C.Item}, .15)
		if r.Stroke and r.Stroke.Color == C.Stroke2 then tw(r.Stroke, {Color = C.Stroke}, .15) end
		if extra then extra() end
	end)
end

