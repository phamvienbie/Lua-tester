-- Icon(name, parent, size, color) -> {Root = ImageLabel|Frame, SetColor = fn, Destroy = fn}
local function Icon(name, parent, size, col)
	col = col or C.Text
	local rawName = tostring(name or ""):gsub("^lucide:", "")
	local key = ICON_ALIAS[rawName:lower()] or rawName:lower()
	local pos = ICON_POS[key] or ICON_POS["tap-ripple"]
	size = math.max(8, math.floor((tonumber(size) or 16) + .5))

	local sheet = getIconSheet()
	if sheet then
		local img = new("ImageLabel", {
			Name = "Icon_" .. rawName,
			Size = UDim2.fromOffset(size, size),
			BackgroundTransparency = 1,
			BorderSizePixel = 0,
			Image = sheet,
			ImageRectSize = Vector2.new(60, 60),
			ImageRectOffset = Vector2.new(pos[1] * 64 + 2, pos[2] * 64 + 2),
			ImageColor3 = col,
			ScaleType = Enum.ScaleType.Fit,
			ResampleMode = Enum.ResamplerMode.Default,
			Parent = parent,
		})
		local api = {Root = img}
		function api.SetColor(c) tw(img, {ImageColor3 = c}, .18) end
		function api.Destroy() img:Destroy() end
		return api
	end

	-- Fallback tối giản nếu executor không hỗ trợ getcustomasset/writefile
	local root = new("Frame", {
		Name = "Icon_" .. rawName, Size = UDim2.fromOffset(size, size), BackgroundTransparency = 1, BorderSizePixel = 0, Parent = parent,
	})
	local ring = new("Frame", {
		AnchorPoint = Vector2.new(.5, .5), Position = UDim2.fromScale(.5, .5),
		Size = UDim2.fromOffset(math.max(6, size - 4), math.max(6, size - 4)),
		BackgroundTransparency = 1, BorderSizePixel = 0, Parent = root,
	}, {pill()})
	local st = stroke(col, 1.5); st.Parent = ring
	local api = {Root = root}
	function api.SetColor(c) tw(st, {Color = c}, .18) end
	function api.Destroy() root:Destroy() end
	return api
end

